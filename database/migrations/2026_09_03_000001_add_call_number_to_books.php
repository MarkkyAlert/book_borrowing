<?php

/**
 * เลขเรียกหนังสือ — "ที่อยู่" ของหนังสือบนชั้น
 *
 * 🎯 ปัญหา: ระบบบอกได้ว่า "มีเล่มนี้ ว่าง 2 เล่ม" แต่บอกไม่ได้ว่า **ไปหยิบที่ไหน**
 *    ห้องสมุดเกินพันเล่ม บรรณารักษ์ต้องจำเองหรือเดินไล่ดูทีละชั้น
 *
 * 🧠 ต่างจาก ISBN คนละหน้าที่กัน:
 *    ISBN         → นี่คือหนังสือเรื่องอะไร (ทั้งโลกใช้เลขเดียวกัน)
 *    เลขเรียก     → อยู่ชั้นไหนใน **ห้องสมุดนี้** (แต่ละแห่งกำหนดเอง)
 *
 * 🔴 VARCHAR ไม่ใช่ตัวเลข และ **ไม่บังคับรูปแบบ**
 *    ห้องสมุดเล็กจำนวนมากไม่ใช้ดิวอี้ ใช้รหัสของตัวเอง เช่น
 *      "371.3 ส236ค 2565"  (ดิวอี้เต็มรูป)
 *      "ก-01-03"            (ตู้ ก ชั้น 1 ช่อง 3)
 *      "นิยาย-045"
 *    ถ้าบังคับรูปแบบดิวอี้ ลูกค้าครึ่งหนึ่งจะใช้ไม่ได้
 *
 * 🧠 NULL ได้ — หนังสือที่ยังไม่ได้ลงเลขเรียกต้องใช้งานได้ตามปกติ
 *    (ลูกค้าที่อัปเกรดมีหนังสืออยู่แล้วทั้งชั้น จะทยอยลงทีหลัง)
 *
 * 📥 $pdo ถูกส่งเข้ามาโดย database/migrate.php
 */

return function (PDO $pdo): string {
    // 🛡️ ตรวจแยกทีละอย่าง — คอลัมน์ / index
    $done = [];

    if ($pdo->query("SHOW COLUMNS FROM `books` LIKE 'call_number'")->rowCount() > 0) {
        $done[] = 'มีคอลัมน์ call_number อยู่แล้ว — ข้าม';
    } else {
        $pdo->exec("ALTER TABLE `books`
                    ADD COLUMN `call_number` VARCHAR(50) DEFAULT NULL
                    COMMENT 'เลขเรียกหนังสือ — ที่อยู่บนชั้น (รูปแบบอิสระ แต่ละห้องสมุดกำหนดเอง)'
                    AFTER `isbn`");
        $done[] = 'เพิ่มคอลัมน์ call_number แล้ว';
    }

    // 📇 index สำหรับ "เรียงตามเลขเรียก" ตอนอ่านชั้น และค้นหาด้วยเลขเรียก
    //    ⚠️ เรียงแบบข้อความ ไม่ใช่แบบตัวเลข — "10" จะมาก่อน "9"
    //       เป็นข้อจำกัดที่ยอมรับ เพราะรูปแบบเลขเรียกอิสระจนแยกส่วนไม่ได้
    if (!$pdo->query("SHOW INDEX FROM `books` WHERE Key_name = 'idx_call_number'")->fetch()) {
        $pdo->exec("ALTER TABLE `books` ADD INDEX `idx_call_number` (`call_number`)");
        $done[] = 'เพิ่ม index idx_call_number แล้ว';
    }

    return implode(' · ', $done);
};
