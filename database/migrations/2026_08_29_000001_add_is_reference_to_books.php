<?php

/**
 * เพิ่มคอลัมน์ is_reference ให้ตาราง books
 *
 * 🎯 หนังสืออ้างอิง (พจนานุกรม สารานุกรม แผนที่) ที่อ่านในห้องสมุดได้อย่างเดียว
 *    ยืมออก/จองไม่ได้ แต่ยัง **ค้นเจอและเห็นบนหน้าเว็บตามปกติ**
 *
 * 🧠 ทำไมไม่ใช้ is_visible แทน: is_visible = ซ่อนจนหาไม่เจอเลย ซึ่งผิดวัตถุประสงค์
 *    หนังสืออ้างอิงต้องค้นเจอ เพื่อให้สมาชิกรู้ว่ามีเล่มนี้แล้วเดินมาอ่านที่ห้องสมุด
 *
 * ⚠️ default = 0 → หนังสือเดิมทุกเล่มยังยืมออกได้เหมือนเดิม ไม่มีอะไรเปลี่ยน
 *    และ **ห้ามตั้งค่าอัตโนมัติจากหมวด "หนังสืออ้างอิง"** เพราะบางห้องสมุด
 *    ใช้ชื่อหมวดนั้นกับหนังสือที่ยืมออกได้
 *
 * 📥 $pdo ถูกส่งเข้ามาโดย database/migrate.php
 */

return function (PDO $pdo): string {
    // 🛡️ ตรวจก่อนว่ามีคอลัมน์อยู่แล้วหรือยัง — migration ต้องรันซ้ำได้โดยไม่พัง
    $exists = $pdo->query("SHOW COLUMNS FROM `books` LIKE 'is_reference'")->rowCount() > 0;
    if ($exists) {
        return 'มีคอลัมน์ is_reference อยู่แล้ว — ข้าม';
    }

    $pdo->exec("ALTER TABLE `books`
                ADD COLUMN `is_reference` TINYINT(1) NOT NULL DEFAULT 0
                COMMENT 'หนังสืออ้างอิง — อ่านในห้องสมุดเท่านั้น ยืม/จองไม่ได้' AFTER `is_visible`");

    return 'เพิ่มคอลัมน์ is_reference ให้ books แล้ว';
};
