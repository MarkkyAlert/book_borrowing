<?php

/**
 * บังคับเปลี่ยนรหัสผ่านครั้งแรก — ปิดช่องรหัสเริ่มต้นร่วม (F-53)
 *
 * 🔴 ปัญหา: `MemberService::importMember()` ตั้งรหัสผ่านเริ่มต้นเหมือนกันทุกคน
 *    และระบบไม่เคยบังคับให้เปลี่ยน — รหัสนั้นจึงเป็นกุญแจที่ใช้ได้ตลอดกาล
 *
 * 🧠 ทำไม rate limit ที่มีอยู่กันไม่ได้: `login.php` นับ attempt แยกรายอีเมล
 *    (`'login_' . md5($email)`) ซึ่งออกแบบมากันคน "เดารหัสของบัญชีเดียวรัว ๆ"
 *    แต่เคสนี้**ไม่มีการเดาเลย** — รู้รหัสอยู่แล้ว ลองอีเมลละครั้งเดียว ไม่แตะเพดานสักอีเมล
 *
 * ==========================================================================
 * 🔴 ส่วนที่สำคัญที่สุดของ migration นี้คือ backfill ไม่ใช่การเพิ่มคอลัมน์
 * ==========================================================================
 * ถ้าเพิ่มคอลัมน์ DEFAULT 0 เฉย ๆ สมาชิกที่ถูกนำเข้าไปแล้วจะยังใช้รหัสเริ่มต้นต่อไป
 * = ลูกค้าที่ติดตั้งไปแล้วไม่ได้อะไรจากการแก้ครั้งนี้เลย
 *
 * จึงต้องไล่ `password_verify()` ทีละคนเพื่อหาว่า**ใครยังใช้รหัสเริ่มต้นอยู่**
 * แล้วติดธงเฉพาะคนนั้น — คนที่ตั้งรหัสเองไปแล้วต้องไม่ถูกรบกวน
 *
 * ⚠️ ไม่มีทางลัด: hash แต่ละแถวมี salt คนละตัว ต่อให้มาจากรหัสเดียวกัน
 *    ต้นทุนคือ bcrypt 1 ครั้ง/สมาชิก (~70ms) — 200 คน ≈ 15 วินาที
 *    ห้องสมุดใหญ่ 5,000 คน ≈ 6 นาที · จึง log ความคืบหน้าให้เห็นว่าไม่ได้ค้าง
 *
 * 📥 $pdo ถูกส่งเข้ามาโดย database/migrate.php
 */

return function (PDO $pdo): string {
    // 🛡️ ตรวจแยกทีละอย่าง (คอลัมน์ / backfill) — เผื่อรันครึ่งทางแล้วพัง
    //    เคยพลาดมาแล้วตอน add_reservation_queue: ผูกคอลัมน์กับ index ไว้ด้วยกัน
    //    พอคอลัมน์มีแล้ว index ยังไม่มี ตัว index จะไม่มีวันถูกสร้าง
    $done = [];

    $columnExisted = $pdo->query("SHOW COLUMNS FROM `users` LIKE 'must_change_password'")->rowCount() > 0;

    if ($columnExisted) {
        $done[] = 'มีคอลัมน์ must_change_password อยู่แล้ว — ข้าม';
    } else {
        $pdo->exec("ALTER TABLE `users`
                    ADD COLUMN `must_change_password` TINYINT(1) NOT NULL DEFAULT 0
                    COMMENT '1 = ต้องเปลี่ยนรหัสผ่านก่อนใช้งาน (ตั้งตอนนำเข้า/admin สร้างให้)'
                    AFTER `role`");
        $done[] = 'เพิ่มคอลัมน์ must_change_password แล้ว';
    }

    // ──────────────────────────────────────────────────────────────────
    // Backfill — ติดธงให้คนที่ยังใช้รหัสเริ่มต้นอยู่
    // ──────────────────────────────────────────────────────────────────
    // 🔁 รันซ้ำได้: ข้ามคนที่ธงขึ้นแล้ว และคนที่เปลี่ยนรหัสไปแล้วก็ verify ไม่ผ่านอยู่ดี
    //    ⚠️ **ห้ามใช้เงื่อนไข "คอลัมน์เพิ่งถูกสร้าง" มาข้าม backfill**
    //    ถ้ารันครั้งแรกแล้วพังกลางทาง คอลัมน์จะมีอยู่แต่ backfill ไม่ครบ
    //    แล้วรอบต่อไปจะข้ามไปเลย = คนที่เหลือไม่ถูกติดธงตลอดกาล
    $defaultPassword = defined('IMPORT_DEFAULT_PASSWORD') ? IMPORT_DEFAULT_PASSWORD : '123456';

    // 🔴 **ไม่จำกัด role** — เกณฑ์เดียวคือ "รหัสของบัญชีนี้คือรหัสเริ่มต้นที่เอกสารประกาศไว้หรือเปล่า"
    //    role ไม่เกี่ยวกับความเสี่ยง ถ้าเกี่ยวก็เกี่ยวในทางกลับกัน:
    //    บัญชี staff/admin ที่ยังใช้รหัสเริ่มต้น **อันตรายกว่าสมาชิกมาก** เพราะเข้าหลังบ้านได้ทั้งระบบ
    //
    //    🧠 ไม่มีความเสี่ยงล็อกผู้ดูแลออกจากระบบ: การถูกบังคับเปลี่ยนไม่ใช่การถูกล็อกออก
    //       เจ้าตัวรู้รหัสเดิมอยู่แล้ว แค่ต้องตั้งรหัสใหม่ก่อนใช้งาน
    //       และ backfill ติดธงเฉพาะบัญชีที่ verify ผ่านกับรหัสเริ่มต้นจริง ๆ เท่านั้น
    //       ผู้ดูแลที่ตั้งรหัสของตัวเองตอนติดตั้ง จะไม่ถูกแตะเลย
    //
    //    📌 ไม่กระทบชุด demo (`sample_data.sql`): install.php baseline migration ทั้งหมด
    //       ตอนติดตั้งใหม่ backfill จึงไม่เคยรันบนเครื่องที่ติดตั้งสด
    //       ตัวนี้ทำงานเฉพาะกับลูกค้าที่ **อัปเกรด** จากเวอร์ชันเก่าเท่านั้น
    $candidates = $pdo->query("
        SELECT `id`, `password`
        FROM `users`
        WHERE `must_change_password` = 0
    ")->fetchAll(PDO::FETCH_ASSOC);

    $total = count($candidates);
    if ($total === 0) {
        $done[] = 'ไม่มีบัญชีที่ต้องตรวจ';
        return implode(' · ', $done);
    }

    // 📢 บอกไว้ก่อนเริ่ม เพราะขั้นนี้กินเวลาเป็นนาทีได้ถ้าสมาชิกเยอะ
    //    ผู้ติดตั้งที่ไม่รู้จะนึกว่าค้างแล้วกด Ctrl+C ทิ้งกลางทาง
    if ($total > 500) {
        echo "    ⏳ ตรวจรหัสผ่านเริ่มต้นของบัญชี {$total} รายการ (bcrypt ~70ms/รายการ ≈ "
            . ceil($total * 0.07) . " วินาที) กรุณารอ...\n";
    }

    $flagged = 0;
    $update = $pdo->prepare("UPDATE `users` SET `must_change_password` = 1 WHERE `id` = ?");

    foreach ($candidates as $i => $row) {
        if (password_verify($defaultPassword, $row['password'])) {
            $update->execute([$row['id']]);
            $flagged++;
        }

        if ($total > 500 && ($i + 1) % 500 === 0) {
            echo '    … ตรวจแล้ว ' . ($i + 1) . "/{$total} รายการ (พบที่ยังใช้รหัสเริ่มต้น {$flagged})\n";
        }
    }

    $done[] = "ตรวจบัญชี {$total} รายการ — ติดธงบังคับเปลี่ยนรหัส {$flagged} รายการ "
        . '(ที่เหลือตั้งรหัสเองไปแล้ว ไม่ถูกรบกวน)';

    return implode(' · ', $done);
};
