<?php

/**
 * หมายเหตุรายเล่ม — สมุดจดของเจ้าหน้าที่
 *
 * 🎯 ปัญหา: ระบบเก็บหนังสือเป็น "ชื่อเรื่อง + จำนวนนับ" ตามรายเล่มไม่ได้
 *    แต่บรรณารักษ์ยังต้องจดว่า "เล่ม 2 ปกขาด · เล่ม 3 หายไปแล้ว" อยู่ดี
 *    เดิมไม่มีที่ให้จด → ไปจดปนใน `description` ซึ่ง **สมาชิกเห็น**
 *
 * 🔴 นี่คือ "สมุดจด" ไม่ใช่ระบบตามรายเล่ม
 *    ระบบไม่ได้ผูกข้อความนี้กับเล่มไหนเลย ไม่มีการตรวจสอบ ไม่มีการนับ
 *    ของจริงต้องมีตาราง book_copies + เปลี่ยน invariant สต็อกทั้งระบบ
 *    (ประเมินไว้แล้วว่าเป็นงานใหญ่ที่ข้อมูลเก่ากู้ไม่ได้ — ดู FINDINGS)
 *
 * 🛡️ เป็นบันทึก **ภายใน** — แสดงเฉพาะฝั่งผู้ดูแล ห้ามโผล่หน้าสาธารณะ
 *
 * 📥 $pdo ถูกส่งเข้ามาโดย database/migrate.php
 */

return function (PDO $pdo): string {
    if ($pdo->query("SHOW COLUMNS FROM `books` LIKE 'copy_notes'")->rowCount() > 0) {
        return 'มีคอลัมน์ copy_notes อยู่แล้ว — ข้าม';
    }

    // 📝 วางต่อจาก description เพราะเป็นข้อความอิสระเหมือนกัน ต่างกันแค่ใครเห็น
    //    ไม่ทำ index — ไม่ได้ใช้ค้นหา และเป็นข้อความยาว
    $pdo->exec("ALTER TABLE `books`
                ADD COLUMN `copy_notes` TEXT DEFAULT NULL
                COMMENT 'บันทึกภายในของเจ้าหน้าที่เกี่ยวกับเล่มแต่ละเล่ม (ข้อความอิสระ ระบบไม่ได้ตามรายเล่มให้)'
                AFTER `description`");

    return 'เพิ่มคอลัมน์ copy_notes แล้ว';
};
