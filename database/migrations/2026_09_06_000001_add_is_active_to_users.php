<?php

/**
 * สถานะ "ยังใช้งาน / เลิกใช้งาน" ของสมาชิก
 *
 * 🎯 ปัญหา (UAT รอบ 2 ข้อ ฒ.5-6): สมาชิกที่เคยยืมแม้ครั้งเดียว **ลบไม่ได้ตลอดกาล**
 *    (ระบบกันไว้เพื่อไม่ให้ประวัติการยืมหาย ซึ่งถูกต้องแล้ว)
 *    แต่ไม่มีทางทำเครื่องหมายว่า "คนนี้ไม่มาแล้ว" เลย
 *    → รายชื่อสมาชิกโตขึ้นทางเดียว ดรอปดาวน์ผู้ยืมยาวขึ้นทุกปีไม่มีวันสั้นลง
 *    นักเรียนที่จบไปแล้ว 5 รุ่นยังปนอยู่กับนักเรียนปัจจุบัน
 *
 * 🧠 ทำไมเป็น flag ไม่ใช่การลบ: ประวัติการยืมต้องอยู่ครบเพื่อทำสถิติสิ้นปี
 *    ปิดใช้งาน = ซ่อนจากงานประจำวัน แต่ข้อมูลเก่ายังอยู่ครบทุกแถว
 *
 * ⚠️ DEFAULT 1 — สมาชิกเดิมทุกคนยังใช้งานได้ตามเดิม ไม่มีใครถูกปิดโดยไม่ตั้งใจ
 *
 * 📥 $pdo ถูกส่งเข้ามาโดย database/migrate.php
 */

return function (PDO $pdo): string {
    if ($pdo->query("SHOW COLUMNS FROM `users` LIKE 'is_active'")->rowCount() > 0) {
        return 'มีคอลัมน์ is_active อยู่แล้ว — ข้าม';
    }

    // 📝 วางต่อจาก role เพราะเป็นเรื่อง "สิทธิ์/สถานะการใช้งาน" เหมือนกัน
    //    ทำ index เพราะดรอปดาวน์ผู้ยืมกรองด้วยคอลัมน์นี้ทุกครั้งที่เปิดหน้าบันทึกการยืม
    $pdo->exec("ALTER TABLE `users`
                ADD COLUMN `is_active` TINYINT(1) NOT NULL DEFAULT 1
                COMMENT '1 = ยังใช้งาน · 0 = เลิกใช้งาน (ซ่อนจากดรอปดาวน์ + ล็อกอินไม่ได้ แต่ประวัติยังอยู่)'
                AFTER `role`");
    $pdo->exec("ALTER TABLE `users` ADD INDEX `idx_is_active` (`is_active`)");

    return 'เพิ่มคอลัมน์ is_active แล้ว (สมาชิกเดิมทุกคนยังใช้งานได้ตามเดิม)';
};
